#!/usr/bin/env python3
"""Self-host the web fonts used by the /challenge/dayN/ concept pages.

Loading fonts from fonts.googleapis.com sends every visitor's IP address to
Google before they have agreed to anything, which EU courts have found to
breach the GDPR (LG München I, 3 O 17493/20). This script copies the same
fonts from the open-source Fontsource packages into /challenge/fonts/ and
writes /challenge/dayN/fonts.css, so the pages load nothing from Google.

Usage (needs the Fontsource packages installed somewhere):
    python3 scripts/self-host-challenge-fonts.py /path/to/node_modules

Only the latin and latin-ext subsets are kept: the pages are in Spanish and
English. Add a page to PAGES when a new day uses Google Fonts, run the script,
then swap its Google <link> tags for <link rel="stylesheet" href="fonts.css">.
"""
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "challenge", "fonts")
SUBSETS = ("latin", "latin-ext")

# family as the page names it -> (package, [(css file, ...)])
FAMILIES = {
    "Outfit": ("@fontsource/outfit", ["300", "400", "500", "600"]),
    "Plus Jakarta Sans": ("@fontsource/plus-jakarta-sans", ["400", "500", "600"]),
    "Montserrat": ("@fontsource/montserrat", ["300", "400", "500", "600"]),
    "Instrument Serif": ("@fontsource/instrument-serif", ["400", "400-italic"]),
    "Hanken Grotesk": ("@fontsource/hanken-grotesk", ["400", "500", "600"]),
    "Cormorant Garamond": ("@fontsource/cormorant-garamond", ["300", "400", "300-italic", "400-italic"]),
    "Jost": ("@fontsource/jost", ["300", "400", "500", "600"]),
    "Manrope": ("@fontsource/manrope", ["400", "500", "600", "700"]),
    "Bricolage Grotesque": ("@fontsource-variable/bricolage-grotesque", ["opsz"]),
    "Inter": ("@fontsource/inter", ["400", "500", "600"]),
    "Space Mono": ("@fontsource/space-mono", ["400", "700"]),
    "DM Serif Display": ("@fontsource/dm-serif-display", ["400", "400-italic"]),
    "Caveat": ("@fontsource/caveat", ["600", "700"]),
}

# day -> families, with the weights each page actually asks Google for
PAGES = {
    1: {"Outfit": ["300", "400", "500", "600"], "Plus Jakarta Sans": ["400", "500", "600"]},
    2: {"Montserrat": ["300", "400", "500", "600"]},
    3: {"Instrument Serif": ["400", "400-italic"], "Hanken Grotesk": ["400", "500", "600"]},
    4: {"Cormorant Garamond": ["300", "400", "300-italic", "400-italic"], "Jost": ["300", "400", "500"]},
    5: {"Instrument Serif": ["400", "400-italic"], "Manrope": ["400", "500", "600", "700"]},
    6: {
        "Bricolage Grotesque": ["opsz"],
        "Inter": ["400", "500", "600"],
        "Space Mono": ["400", "700"],
        "Instrument Serif": ["400", "400-italic"],
    },
    7: {"DM Serif Display": ["400", "400-italic"], "Caveat": ["600", "700"], "Jost": ["400", "500", "600"]},
}

BLOCK = re.compile(r"/\*\s*([^*]+?)\s*\*/\s*(@font-face\s*\{[^}]*\})", re.S)


def faces(modules, family, css_name):
    pkg = FAMILIES[family][0]
    path = os.path.join(modules, pkg, css_name + ".css")
    css = open(path, encoding="utf-8").read()
    out = []
    for label, block in BLOCK.findall(css):
        subset = next((s for s in sorted(SUBSETS, key=len, reverse=True) if "-" + s + "-" in label), None)
        if subset is None:
            continue
        src = re.search(r"url\(\./files/([^)]+\.woff2)\)", block).group(1)
        shutil.copyfile(os.path.join(modules, pkg, "files", src), os.path.join(OUT, src))
        block = re.sub(r"src:[^;]+;", "src: url(/challenge/fonts/%s) format('woff2');" % src, block)
        block = re.sub(r"font-family:[^;]+;", "font-family: '%s';" % family, block)
        out.append(block)
    if not out:
        raise SystemExit("no latin faces in " + path)
    return out


def main():
    modules = sys.argv[1] if len(sys.argv) > 1 else "node_modules"
    os.makedirs(OUT, exist_ok=True)
    for day, fams in PAGES.items():
        blocks = []
        for family, files in fams.items():
            for name in files:
                blocks.extend(faces(modules, family, name))
        css = (
            "/* Self-hosted fonts for this page (Fontsource, SIL Open Font License).\n"
            "   Generated by scripts/self-host-challenge-fonts.py. Nothing loads from Google. */\n"
            + "\n".join(blocks)
            + "\n"
        )
        with open(os.path.join(ROOT, "challenge", "day%d" % day, "fonts.css"), "w", encoding="utf-8") as fh:
            fh.write(css)
        print("day%d: %d faces" % (day, len(blocks)))


if __name__ == "__main__":
    main()
